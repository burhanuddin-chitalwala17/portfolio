// Builds SQL for a database's SQL editor (e.g. Supabase → SQL Editor) from the migrations in drizzle/:
// - supabase/setup.sql: every migration, for a new, empty database
// - supabase/migrations/<tag>.sql: one migration each, for a database that already has the earlier ones
// Each also records the migration the way `npm run db:migrate` does, so both ways of updating stay in step.
// Regenerate after `npm run db:generate`: npm run db:setup-sql
import crypto from "node:crypto";
import fs from "node:fs";

const folder = new URL("../drizzle/", import.meta.url);
const output = new URL("../supabase/", import.meta.url);
const journal = JSON.parse(fs.readFileSync(new URL("meta/_journal.json", folder), "utf8"));

const HEADER = [
  "-- Generated by scripts/build-setup-sql.mjs from drizzle/. Do not edit by hand.",
  "-- The SQL editor runs the whole script as one transaction, so a failure leaves nothing half-made.",
  "-- (No explicit BEGIN/COMMIT: after an error, those would leave the editor's connection holding locks.)",
];
const BOOKKEEPING_TABLE = [
  "CREATE SCHEMA IF NOT EXISTS drizzle;",
  "CREATE TABLE IF NOT EXISTS drizzle.__drizzle_migrations (id SERIAL PRIMARY KEY, hash text NOT NULL, created_at bigint);",
];

function readMigration(entry) {
  const sql = fs.readFileSync(new URL(`${entry.tag}.sql`, folder), "utf8");
  const statements = sql
    .split("--> statement-breakpoint")
    .map((statement) => statement.trim())
    .filter(Boolean)
    .map((statement) => (statement.endsWith(";") ? statement : `${statement};`));
  const hash = crypto.createHash("sha256").update(sql).digest("hex");
  return { statements, record: `('${hash}', ${entry.when})` };
}

const migrations = journal.entries.map((entry) => ({ entry, ...readMigration(entry) }));

fs.writeFileSync(
  new URL("setup.sql", output),
  [
    ...HEADER,
    "-- Paste into the SQL editor and run once on an empty database.",
    ...migrations.flatMap(({ entry, statements }) => [`\n-- ${entry.tag}`, ...statements]),
    "\n-- Record the migrations as applied (same table drizzle-kit migrate uses).",
    ...BOOKKEEPING_TABLE,
    `INSERT INTO drizzle.__drizzle_migrations (hash, created_at) VALUES\n  ${migrations.map((m) => m.record).join(",\n  ")};\n`,
  ].join("\n")
);

fs.mkdirSync(new URL("migrations/", output), { recursive: true });
for (const { entry, statements, record } of migrations) {
  fs.writeFileSync(
    new URL(`migrations/${entry.tag}.sql`, output),
    [
      ...HEADER,
      "-- Run once, in number order, on a database set up before this migration existed.",
      "",
      ...statements,
      "",
      ...BOOKKEEPING_TABLE,
      `INSERT INTO drizzle.__drizzle_migrations (hash, created_at) VALUES ${record};\n`,
    ].join("\n")
  );
}
console.log(`Wrote supabase/setup.sql and supabase/migrations/ (${migrations.length} migrations)`);
